/** Resolve a key path like "items.new" to a translation string */
function resolve(dict: Dict, path: string): string | null {
  const parts = path.split(".");
  let cur: string | Dict = dict;
  for (const p of parts) {
    if (typeof cur !== "object" || cur === null) return null;
    cur = cur[p];
    if (cur === undefined) return null;
  }
  return typeof cur === "string" ? cur : null;
}

/** Translate function with optional `{key}` interpolation */
export function translate(locale: Locale, key: string, vars?: Record<string, string | number>): string {
  let text = resolve(TRANSLATIONS[locale], key) || resolve(TRANSLATIONS.en, key) || key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(`{${k}}`, String(v));
    }
  }
  return text;
}
